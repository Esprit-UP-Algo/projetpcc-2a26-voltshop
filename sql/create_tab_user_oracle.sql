-- SQL: create TAB_USER table for authentication and 2FA
-- Run as the schema owner (for Oracle)

CREATE TABLE TAB_USER (
  ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USERNAME      VARCHAR2(100) NOT NULL,
  PASSWORD      VARCHAR2(512) NOT NULL,
  TOTP_SECRET   VARCHAR2(128),
  PASSWORD_ALGO VARCHAR2(50) DEFAULT 'plain', -- 'plain' for now, change to 'sha256' or 'argon2' later
  ROLE          VARCHAR2(50) DEFAULT 'worker',
  IS_ACTIVE     NUMBER(1) DEFAULT 1,
  FAILED_ATTEMPTS NUMBER DEFAULT 0,
  LOCKED_UNTIL  TIMESTAMP,
  LAST_LOGIN    TIMESTAMP,
  CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
  UPDATED_AT    TIMESTAMP
);

-- Unique index on username
CREATE UNIQUE INDEX IDX_TAB_USER_USERNAME ON TAB_USER (USERNAME);

